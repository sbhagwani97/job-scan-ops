#!/usr/bin/env node
// Deterministic tracker maintenance for job-scan. Zero dependencies (Node 18+).
// State lives in <dir>/tracker.json; <dir>/tracker.md is re-rendered after every change.
//
// Usage: node tracker.mjs <command> [args] [--dir job-scan]
//   init [--portals-src file]                 create dir structure, empty tracker, copy portals
//   filter --jobs f --out f --run ID          drop already-known jobs, touch lastSeen, write new ones
//   merge  --scored f --run ID [--threshold 4] [--sources a,b] [--complete a,b]
//   add    --job f [--threshold 4]             add/update one job with its score (used by evaluate)
//   set-status <id> <Status> [--note text]
//   list [--status S] [--min-score N] [--json]
//   show <id>
//   render

import fs from 'node:fs';
import path from 'node:path';

const STATUSES = ['Shortlisted', 'Prepared', 'Applied', 'Interview', 'Offer', 'Rejected', 'Skipped', 'Closed'];
const ACTIVE = ['Shortlisted', 'Prepared', 'Applied', 'Interview', 'Offer'];

function parseArgs(argv) {
  const pos = [], flags = {};
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a.startsWith('--')) {
      const k = a.slice(2), n = argv[i + 1];
      if (n === undefined || n.startsWith('--')) flags[k] = true;
      else { flags[k] = n; i++; }
    } else pos.push(a);
  }
  return { pos, flags };
}

const { pos, flags } = parseArgs(process.argv.slice(2));
const cmd = pos[0];
const dir = flags.dir || 'job-scan';
const JSON_PATH = path.join(dir, 'tracker.json');
const MD_PATH = path.join(dir, 'tracker.md');
const today = () => new Date().toISOString().slice(0, 10);
const norm = (s) => String(s || '').toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim();
const dupeKey = (j) => `${norm(j.company)}|${norm(j.title)}|${norm(j.location)}`;
const readJson = (f) => JSON.parse(fs.readFileSync(f, 'utf8').replace(/^\uFEFF/, ''));
const die = (m) => { console.error('error: ' + m); process.exit(1); };

function load() {
  if (!fs.existsSync(JSON_PATH)) return { jobs: {}, scans: [], pending: {} };
  const t = readJson(JSON_PATH);
  t.pending ||= {};
  return t;
}

function save(t) {
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(JSON_PATH, JSON.stringify(t, null, 2));
  fs.writeFileSync(MD_PATH, render(t));
}

const cell = (v) => String(v ?? '').replace(/\|/g, '\\|').replace(/\r?\n/g, ' ').trim();

function table(rows) {
  if (!rows.length) return '_none_\n';
  let out = '| ID | Company | Role | Location | Score | Source | Status | First seen | Last seen | Notes |\n';
  out += '|---|---|---|---|---|---|---|---|---|---|\n';
  for (const j of rows) {
    out += `| ${j.id} | ${cell(j.company)} | [${cell(j.title)}](${j.url}) | ${cell(j.location)} | ${j.score ?? ''} | ${cell(j.source)} | ${j.status} | ${j.firstSeen} | ${j.lastSeen} | ${cell(j.notes)} |\n`;
  }
  return out;
}

function render(t) {
  const jobs = Object.values(t.jobs);
  const by = (pred) => jobs.filter(pred).sort((a, b) => (b.score ?? 0) - (a.score ?? 0));
  const counts = STATUSES.map((s) => `${s}: ${jobs.filter((j) => j.status === s).length}`).join(', ');
  let md = '# Job Tracker\n\n';
  md += `_Generated by job-scan on ${today()}. Change statuses with \`/job-scan:tracker set <id> <status>\`; manual edits to this file are overwritten._\n\n`;
  md += `**Total tracked:** ${jobs.length}  \n**${counts}**\n\n`;
  md += '## Active pipeline\n\n' + table(by((j) => ACTIVE.includes(j.status)));
  md += '\n## Below threshold / skipped\n\n' + table(by((j) => j.status === 'Skipped'));
  md += '\n## Rejected / closed\n\n' + table(by((j) => ['Rejected', 'Closed'].includes(j.status)));
  md += '\n## Scan log\n\n| Date | Run | Sources | Found | Already known | New | Shortlisted | Closed |\n|---|---|---|---|---|---|---|---|\n';
  for (const s of [...t.scans].reverse()) {
    md += `| ${s.date} | ${s.run} | ${cell((s.sources || []).join(', '))} | ${s.found} | ${s.known} | ${s.new} | ${s.shortlisted} | ${s.closed} |\n`;
  }
  return md;
}

function findJob(t, idArg) {
  if (!idArg) die('job id required');
  const ids = Object.keys(t.jobs).filter((i) => i === idArg || i.startsWith(idArg));
  if (ids.length !== 1) die(ids.length ? `ambiguous id "${idArg}": ${ids.join(', ')}` : `no job with id "${idArg}"`);
  return t.jobs[ids[0]];
}

const commands = {
  init() {
    for (const d of ['cv/original', 'applications']) fs.mkdirSync(path.join(dir, d), { recursive: true });
    if (flags['portals-src'] && !fs.existsSync(path.join(dir, 'portals.json'))) {
      fs.copyFileSync(flags['portals-src'], path.join(dir, 'portals.json'));
    }
    const t = load();
    save(t);
    console.log(JSON.stringify({ ok: true, dir }));
  },

  filter() {
    if (!flags.jobs || !flags.out || !flags.run) die('--jobs, --out and --run are required');
    const raw = readJson(flags.jobs);
    const input = Array.isArray(raw) ? raw : raw.jobs || [];
    const t = load();
    const byKey = new Map(Object.values(t.jobs).map((j) => [dupeKey(j), j]));
    const batchSeen = new Set();
    const fresh = [];
    let known = 0;
    for (const j of input) {
      if (!j.id) j.id = hashId(j.url || dupeKey(j));
      const k = dupeKey(j);
      if (batchSeen.has(j.id) || batchSeen.has(k)) continue;
      batchSeen.add(j.id); batchSeen.add(k);
      const existing = t.jobs[j.id] || byKey.get(k);
      if (existing) {
        known++;
        existing.lastSeen = today();
        existing.lastSeenRun = flags.run;
        if (existing.status === 'Closed') { existing.status = existing.qualified ? 'Shortlisted' : 'Skipped'; }
      } else fresh.push(j);
    }
    t.pending[flags.run] = { found: fresh.length + known, known, date: today() };
    save(t);
    fs.writeFileSync(flags.out, JSON.stringify(fresh, null, 2));
    console.log(JSON.stringify({ found: fresh.length + known, known, new: fresh.length, out: flags.out }));
  },

  merge() {
    if (!flags.scored || !flags.run) die('--scored and --run are required');
    const threshold = Number(flags.threshold ?? 4);
    // Optional: join score results with job data by id. --jobs and --scored accept comma-separated files.
    const readMany = (spec) => String(spec).split(',').filter(Boolean).flatMap((f) => {
      const r = readJson(f.trim());
      return Array.isArray(r) ? r : r.jobs || [];
    });
    const jobData = new Map((flags.jobs ? readMany(flags.jobs) : []).map((j) => [j.id, j]));
    const scoredAll = readMany(flags.scored).map((s) => ({ ...(jobData.get(s.id) || {}), ...s }));
    const t = load();
    let added = 0, shortlisted = 0, closed = 0;
    for (const s of scoredAll) {
      if (!s.id || typeof s.score !== 'number' || !s.url) continue;
      const qualified = !s.knockout && s.score >= threshold;
      t.jobs[s.id] = {
        id: s.id, company: s.company, title: s.title, location: s.location, url: s.url,
        source: s.source, postedDate: s.postedDate || null,
        score: s.score, rationale: s.rationale || '', matched: s.matched || [], gaps: s.gaps || [],
        knockout: !!s.knockout, qualified,
        status: qualified ? 'Shortlisted' : 'Skipped',
        firstSeen: today(), lastSeen: today(), lastSeenRun: flags.run,
        notes: s.knockout ? `knockout: ${s.knockoutReason || 'requirement violated'}` : '',
        description: String(s.description || '').slice(0, 8000),
      };
      added++;
      if (qualified) shortlisted++;
    }
    const complete = new Set(String(flags.complete || '').split(',').map((x) => x.trim()).filter(Boolean));
    if (complete.size) {
      for (const j of Object.values(t.jobs)) {
        if (['Shortlisted', 'Skipped'].includes(j.status) && complete.has(j.source) && j.lastSeenRun !== flags.run) {
          j.status = 'Closed'; closed++;
        }
      }
    }
    const p = t.pending[flags.run] || { found: added, known: 0 };
    delete t.pending[flags.run];
    t.scans.push({
      date: today(), run: flags.run,
      sources: String(flags.sources || '').split(',').map((x) => x.trim()).filter(Boolean),
      found: p.found, known: p.known, new: added, shortlisted, closed,
    });
    save(t);
    console.log(JSON.stringify({ new: added, shortlisted, closed, threshold }));
  },

  // Add or update a single job from a JSON file that already carries its score.
  // Used by /job-scan:evaluate --track. Existing manually-set statuses are preserved.
  add() {
    if (!flags.job) die('--job is required');
    const raw = readJson(flags.job);
    const j = Array.isArray(raw) ? raw[0] : raw;
    if (!j || !j.title || !j.url) die('job JSON must include at least title and url');
    if (!j.id) j.id = hashId(j.url || dupeKey(j));
    const threshold = Number(flags.threshold ?? 4);
    const t = load();
    const existing = t.jobs[j.id];
    const score = typeof j.score === 'number' ? j.score : existing?.score ?? null;
    const knockout = !!j.knockout;
    const qualified = score !== null && !knockout && score >= threshold;
    const manualStatus = existing && !['Shortlisted', 'Skipped'].includes(existing.status);
    const status = manualStatus ? existing.status : (qualified ? 'Shortlisted' : 'Skipped');
    t.jobs[j.id] = {
      ...(existing || {}),
      id: j.id,
      company: j.company || existing?.company || 'Unknown',
      title: j.title,
      location: j.location || existing?.location || '',
      url: j.url,
      source: j.source || existing?.source || 'manual',
      postedDate: j.postedDate || existing?.postedDate || null,
      score,
      rationale: j.rationale || existing?.rationale || '',
      matched: j.matched || existing?.matched || [],
      gaps: j.gaps || existing?.gaps || [],
      knockout,
      qualified,
      status,
      firstSeen: existing?.firstSeen || today(),
      lastSeen: today(),
      notes: knockout ? `knockout: ${j.knockoutReason || 'requirement violated'}` : (existing?.notes || ''),
      description: String(j.description || existing?.description || '').slice(0, 8000),
    };
    save(t);
    console.log(JSON.stringify({ id: j.id, status, score, qualified }));
  },

  // Export tracked jobs (with descriptions) for re-scoring after a CV/profile change.
  export() {
    if (!flags.out) die('--out is required');
    const want = String(flags.statuses || 'Shortlisted,Skipped').split(',').map((s) => s.trim().toLowerCase());
    const jobs = Object.values(load().jobs).filter((j) => want.includes(j.status.toLowerCase()));
    fs.writeFileSync(flags.out, JSON.stringify(jobs.map((j) => ({
      id: j.id, company: j.company, title: j.title, location: j.location, url: j.url,
      source: j.source, description: j.description,
    })), null, 2));
    console.log(JSON.stringify({ exported: jobs.length, out: flags.out }));
  },

  // Apply new scores to existing jobs (--scored), or with no --scored just re-apply --threshold to stored scores.
  // Statuses you set manually (Prepared, Applied, ...) are preserved;
  // only Shortlisted/Skipped jobs move according to the score.
  rescore() {
    const threshold = Number(flags.threshold ?? 4);
    const t = load();
    let updated = 0, promoted = 0, demoted = 0;
    const settle = (j) => {
      j.qualified = !j.knockout && j.score >= threshold;
      if (['Shortlisted', 'Skipped'].includes(j.status)) {
        const next = j.qualified ? 'Shortlisted' : 'Skipped';
        if (next !== j.status) { j.qualified ? promoted++ : demoted++; j.status = next; }
      }
    };
    if (!flags.scored) {
      for (const j of Object.values(t.jobs)) if (typeof j.score === 'number') { settle(j); updated++; }
    }
    for (const f of String(flags.scored || '').split(',').filter(Boolean)) {
      const r = readJson(f.trim());
      for (const s of Array.isArray(r) ? r : r.jobs || []) {
        const j = t.jobs[s.id];
        if (!j || typeof s.score !== 'number') continue;
        j.previousScore = j.score;
        j.score = s.score; j.rationale = s.rationale || ''; j.matched = s.matched || []; j.gaps = s.gaps || [];
        j.knockout = !!s.knockout;
        j.notes = j.knockout ? `knockout: ${s.knockoutReason || 'requirement violated'}` : (j.notes || '').replace(/^knockout:[^;]*;?\s*/, '');
        settle(j);
        updated++;
      }
    }
    save(t);
    console.log(JSON.stringify({ updated, promoted, demoted, threshold }));
  },

  // Wipe tracked jobs and scan log (a timestamped backup is kept next to tracker.json).
  clear() {
    const t = load();
    const backup = path.join(dir, `tracker.backup-${new Date().toISOString().replace(/[:.]/g, '-')}.json`);
    fs.writeFileSync(backup, JSON.stringify(t, null, 2));
    save({ jobs: {}, scans: [], pending: {} });
    console.log(JSON.stringify({ cleared: Object.keys(t.jobs).length, backup }));
  },

  'set-status'() {
    const t = load();
    const j = findJob(t, pos[1]);
    const want = STATUSES.find((s) => s.toLowerCase() === String(pos[2] || '').toLowerCase());
    if (!want) die(`status must be one of: ${STATUSES.join(', ')}`);
    j.status = want;
    if (want === 'Applied') j.appliedDate = today();
    if (flags.note && flags.note !== true) j.notes = [j.notes, flags.note].filter(Boolean).join('; ');
    save(t);
    console.log(JSON.stringify({ id: j.id, status: j.status }));
  },

  list() {
    const t = load();
    let jobs = Object.values(t.jobs);
    if (flags.status) jobs = jobs.filter((j) => j.status.toLowerCase() === String(flags.status).toLowerCase());
    if (flags['min-score']) jobs = jobs.filter((j) => (j.score ?? 0) >= Number(flags['min-score']));
    jobs.sort((a, b) => (b.score ?? 0) - (a.score ?? 0));
    if (flags.json) {
      console.log(JSON.stringify(jobs.map(({ description, ...r }) => r), null, 2));
    } else {
      for (const j of jobs) console.log(`${j.id}  ${j.score}  ${j.status.padEnd(11)} ${j.company} - ${j.title} (${j.location})`);
      if (!jobs.length) console.log('(no matching jobs)');
    }
  },

  show() {
    console.log(JSON.stringify(findJob(load(), pos[1]), null, 2));
  },

  render() {
    save(load());
    console.log(JSON.stringify({ ok: true, file: MD_PATH }));
  },
};

import { createHash } from 'node:crypto';
function hashId(s) { return createHash('sha1').update(String(s)).digest('hex').slice(0, 10); }

if (!commands[cmd]) die(`unknown command "${cmd}". Commands: ${Object.keys(commands).join(', ')}`);
commands[cmd]();
